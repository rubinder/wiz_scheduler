"""Glue column lists for the lake's tables, generated from schemas.TABLES
(#259 step 10), so the pyarrow schemas stay the one source of the columns.

Regenerate after any schema change:

    python -m backend.analytics.glue_columns > terraform/analytics_columns.tf.json

tests/analytics/test_glue_columns.py fails when the checked-in file is
stale. The partition column `dt` is not in the schemas and is declared by
the Glue tables in terraform/analytics.tf.
"""

import json
import sys

import pyarrow as pa

from backend.analytics.schemas import TABLES


def glue_type(t: pa.DataType) -> str:
    """The Hive/Glue type Athena reads a Parquet column of pyarrow type `t` as."""
    if pa.types.is_timestamp(t):
        return "timestamp"
    if pa.types.is_decimal(t):
        return f"decimal({t.precision},{t.scale})"
    if pa.types.is_boolean(t):
        return "boolean"
    if pa.types.is_int8(t):
        return "tinyint"
    if pa.types.is_int16(t):
        return "smallint"
    if pa.types.is_int32(t):
        return "int"
    if pa.types.is_int64(t):
        return "bigint"
    if pa.types.is_float32(t):
        return "float"
    if pa.types.is_float64(t):
        return "double"
    if pa.types.is_string(t) or pa.types.is_large_string(t):
        return "string"
    if pa.types.is_date(t):
        return "date"
    if pa.types.is_binary(t) or pa.types.is_large_binary(t):
        return "binary"
    raise ValueError(f"no Glue type for pyarrow type {t}")


def columns() -> dict[str, list[dict[str, str]]]:
    """{table: [{"name", "type"}, ...]} in schema order."""
    return {table: [{"name": f.name, "type": glue_type(f.type)} for f in schema]
            for table, schema in TABLES.items()}


def render() -> str:
    """The terraform/analytics_columns.tf.json text: one local, read by
    terraform/analytics.tf."""
    doc = {
        "//": "Generated by `python -m backend.analytics.glue_columns`; do not edit.",
        "locals": {"analytics_columns": columns()},
    }
    return json.dumps(doc, indent=2) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render())
